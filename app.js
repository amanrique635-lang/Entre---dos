function buildInitialDeck(key) {
  const cards = gameData[key].cards;
  
  if (key !== "extremo") {
    return shuffle(cards);
  }

  // Progresión interna de EXTREMO dividida en 3 grupos inamovibles.
  const groupA = shuffle(cards.slice(0, 5));
  const groupB = shuffle(cards.slice(5, 10));
  const groupC = shuffle(cards.slice(10, 15));

  return [...groupA, ...groupB, ...groupC];
}

function launchLevel(key) {
  state.level = key;
  state.total = gameData[key].cards.length;
  state.completed = 0;
  state.turn = 0;
  state.passes = 0;
  state.deferred = [];
  state.unseen = buildInitialDeck(key);
  state.current = drawNextCard();
  $("#completion").classList.remove("show");
  $("#challengeCard").style.display = "grid";
  navigate("game");
  renderCard();
}
function startLevel(key) {
  if (key === "extremo") {
    state.pendingLevel = key;
    $("#extremeIntro").classList.add("show");
    return;
  }
  launchLevel(key);
}

function drawNextCard(excludeId = null) {
  if (!state.unseen.length && state.deferred.length) {
    state.unseen = shuffle(state.deferred);
    state.deferred = [];
    if (excludeId && state.unseen.length > 1 && state.unseen[0].id === excludeId) {
      const swapIndex = state.unseen.findIndex(c => c.id !== excludeId);
      [state.unseen[0], state.unseen[swapIndex]] = [state.unseen[swapIndex], state.unseen[0]];
    }
  }
  return state.unseen.shift() || null;
}

function actorFor(card) {
  if (card.for === "both") return "Los dos";
  return state.names[state.turn % 2];
}
function pendingCount() { return state.total - state.completed; }

