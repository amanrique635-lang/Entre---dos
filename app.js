function toggleFavorite() {
  const card = state.current;
  if (!card) return;
  if (state.favorites.has(card.id)) {
    state.favorites.delete(card.id);
    showToast("Quitada de favoritos");
  } else {
    state.favorites.add(card.id);
    showToast("Guardada en favoritos");
  }
  saveFavorites();
  updateFavoriteUI();
}
function updateFavoriteUI() {
  const card = state.current;
  const on = card && state.favorites.has(card.id);
  $("#favoriteHeart").textContent = on ? "♥" : "♡";
  $("#favoriteHeart").classList.toggle("on", !!on);
  $("#favBtn").querySelector(".ico").textContent = on ? "♥" : "♡";
}
function findCard(id) {
  for (const key of levelOrder) {
    const card = gameData[key].cards.find(x => x.id === id);
    if (card) return { key, card };
  }
  return null;
}
function renderFavorites() {
  const list = $("#favoritesList");
  list.innerHTML = "";
  const items = [...state.favorites].map(findCard).filter(Boolean);
  if (!items.length) {
    list.innerHTML = `<div class="empty glass"><div style="font-size:2rem">♡</div><h3 style="margin:10px 0 6px">Aún no hay favoritos</h3><div class="muted">Marca una carta con el corazón durante el juego.</div></div>`;
    return;
  }
  items.forEach(({ key, card }) => {
    const item = document.createElement("div");
    item.className = "fav-item glass";
    item.innerHTML = `<div><div class="lvl">${gameData[key].name} · ${card.type}</div><p>${card.text}</p></div><button class="remove-fav" aria-label="Quitar de favoritos">♥</button>`;
    item.querySelector("button").addEventListener("click", () => {
      state.favorites.delete(card.id);
      saveFavorites();
      renderFavorites();
    });
    list.appendChild(item);
  });
}

function openTimer() {
  const card = state.current;
  const suggested = card && card.duration
    ? Math.min(60, Math.max(15, [15, 30, 60].reduce((a, b) => Math.abs(b - card.duration) < Math.abs(a - card.duration) ? b : a, 30)))
    : 30;
  state.timerDuration = suggested;
  resetTimerVisual(suggested);
  $("#timerModal").classList.add("show");
}
function closeTimer() {
  clearInterval(state.timerId);
  state.timerId = null;
  $("#timerModal").classList.remove("show");
}
function resetTimerVisual(seconds) {
  $("#timerNumber").textContent = seconds;
  $("#timerCircle").style.setProperty("--p", "0deg");
  $("#timerCircle").classList.remove("done");
  $("#timerNote").textContent = "Toca una duración para comenzar.";
}
function startTimer(seconds) {
  clearInterval(state.timerId);
  state.timerDuration = seconds;
  state.timerEnds = Date.now() + seconds * 1000;
  $("#timerNote").textContent = "Tiempo en marcha";
  const tick = () => {
    const left = Math.max(0, Math.ceil((state.timerEnds - Date.now()) / 1000));
    const elapsed = seconds - left;
    $("#timerNumber").textContent = left;
    $("#timerCircle").style.setProperty("--p", `${Math.min(360, (elapsed / seconds) * 360)}deg`);
    if (left <= 0) {
      clearInterval(state.timerId);
      state.timerId = null;
      $("#timerNote").textContent = "Tiempo";
      $("#timerCircle").classList.add("done");
    }
  };
  tick();
  state.timerId = setInterval(tick, 200);
}

