function buildInitialDeck(key) {
  const cards = gameData[key].cards;

  state.mandatoryCards = [];
  state.mandatorySlots = [];
  state.mandatoryIndex = 0;
  state.bothUnlockAt = gameData[key].bothUnlockAt || 0;
  state.noRepeatSession = key === "extremo" || key === "poses" || key === "fotos";

  if (key === "extremo") {
    state.mandatoryCards = cards.filter(card => card.mandatory);
    state.mandatorySlots = [4, 9, 14, 19];
    return shuffle(cards.filter(card => !card.mandatory));
  }

  if (key === "fotos") {
    state.photoStage = "underwear";
    state.photoUnderwearCompleted = 0;
    state.photoSkinCompleted = 0;
    state.photoUnderwearDeck = shuffle(cards.filter(card => card.photoCategory === "underwear"));
    state.photoSkinDeck = shuffle(cards.filter(card => card.photoCategory === "skin"));
    return [...state.photoUnderwearDeck];
  }

  state.photoStage = null;
  state.photoUnderwearCompleted = 0;
  state.photoSkinCompleted = 0;
  state.photoUnderwearDeck = [];
  state.photoSkinDeck = [];
  return shuffle(cards);
}

