function advanceCard() {
  const card = state.current;
  if (!card) return;

  if (state.level === "fotos") {
    state.photoTurnIndex = state.photoTurnIndex === 0 ? 1 : 0;
    state.completed++;
    state.current = null;

    if (state.photoStage === "underwear") {
      state.photoUnderwearCompleted++;
      if (state.photoUnderwearCompleted >= 10) {
        $("#photosTransition").classList.add("show");
        return;
      }
    } else if (state.photoStage === "skin") {
      state.photoSkinCompleted++;
      if (state.photoSkinCompleted >= 10) return completeLevel();
    }

    state.current = drawNextCard();
    if (!state.current) return noMoreCards();
    renderCard();
    return;
  }

  if (card.for !== "both") {
    if (Number.isInteger(card.actorIndex)) {
      state.turn = card.actorIndex === 0 ? 1 : 0;
    } else {
      state.turn++;
    }
  }
  state.completed++;
  state.current = null;

  if (state.completed >= state.total) return completeLevel();

  state.current = drawNextCard();
  if (!state.current) return noMoreCards();
  renderCard();
}

function passCard() {
  const card = state.current;
  if (!card) return;

  if (state.level === "fotos" && state.photoStage === "underwear") {
    showToast("Paso se habilita a partir de la carta 12");
    return;
  }

  state.passes++;

  if (state.noRepeatSession) {
    state.skipped.push(card);
    state.current = drawNextCard(card.id);
    if (!state.current) return noMoreCards();
    showToast("Paso · no suma y esta carta no se repite");
    renderCard();
    return;
  }

  const otherPending = state.unseen.length + state.deferred.length;
  if (otherPending === 0) {
    state.passes--;
    showToast("Es el último reto pendiente; Paso no lo cuenta.");
    return;
  }

  state.deferred.push(card);
  state.current = drawNextCard(card.id);
  showToast("Paso · no suma y muestra otro reto");
  renderCard();
}

