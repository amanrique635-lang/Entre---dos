function registerDraw(card) {
  if (!card) return null;
  state.seen.add(card.id);
  state.shownCount++;
  return card;
}

function takeMandatoryIfDue() {
  if (state.level !== "extremo") return null;
  if (state.mandatoryIndex >= state.mandatoryCards.length) return null;

  const dueAtShownCard = state.mandatorySlots[state.mandatoryIndex];
  const nextShownCard = state.shownCount + 1;
  if (nextShownCard < dueAtShownCard) return null;

  return state.mandatoryCards[state.mandatoryIndex++];
}

