function advanceCard() {
  const card = state.current;
  if (!card) return;

  if (state.level === "fotos") {
    state.completed++;
    state.current = null;

    if (state.photoStage === "underwear") {
      state.photoUnderwearCompleted++;
      if (state.photoUnderwearCompleted >= 10) {
        $("#photosTransition").classList.add("show");
        return;
      }
    } else if (state.photoStage === "skin") {
      state.photoSkinCompleted++;
      if (state.photoSkinCompleted >= 10) return completeLevel();
    }

    state.current = drawNextCard();
    if (!state.current) return noMoreCards();
    renderCard();
    return;
  }

  if (card.for !== "both") {
    if (Number.isInteger(card.actorIndex)) {
      state.turn = card.actorIndex === 0 ? 1 : 0;
    } else {
      state.turn++;
    }
  }
  state.completed++;
  state.current = null;

  if (state.completed >= state.total) return completeLevel();

  state.current = drawNextCard();
  if (!state.current) return noMoreCards();
  renderCard();
}

