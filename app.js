function startTimer(seconds) {
  clearInterval(state.timerId);
  state.timerDuration = seconds;
  state.timerEnds = Date.now() + seconds * 1000;
  $("#timerNote").textContent = "Tiempo en marcha";
  const tick = () => {
    const left = Math.max(0, Math.ceil((state.timerEnds - Date.now()) / 1000));
    const elapsed = seconds - left;
    $("#timerNumber").textContent = left;
    $("#timerCircle").style.setProperty("--p", `${Math.min(360, (elapsed / seconds) * 360)}deg`);
    if (left <= 0) {
      clearInterval(state.timerId);
      state.timerId = null;
      $("#timerNote").textContent = "Tiempo";
      $("#timerCircle").classList.add("done");
    }
  };
  tick();
  state.timerId = setInterval(tick, 200);
}

