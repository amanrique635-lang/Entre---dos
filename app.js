function buildInitialDeck(key) {
  const cards = gameData[key].cards;

  state.mandatoryCards = [];
  state.mandatorySlots = [];
  state.mandatoryIndex = 0;
  state.bothUnlockAt = gameData[key].bothUnlockAt || 0;
  state.noRepeatSession = key === "extremo" || key === "fotos";

  if (key === "extremo") {
    state.mandatoryCards = cards.filter(card => card.mandatory);
    state.mandatorySlots = [3, 7, 11, 15];
    return shuffle(cards.filter(card => !card.mandatory));
  }

  return shuffle(cards);
}

function launchLevel(key) {
  const data = gameData[key];
  state.level = key;
  state.total = data.target || data.cards.length;
  state.bankTotal = data.cards.length;
  state.completed = 0;
  state.turn = 0;
  state.passes = 0;
  state.deferred = [];
  state.skipped = [];
  state.seen = new Set();
  state.unseen = buildInitialDeck(key);
  state.current = drawNextCard();
  $("#completion").classList.remove("show");
  $("#challengeCard").style.display = "grid";
  navigate("game");
  renderCard();
}

function startLevel(key) {
  if (key === "extremo") {
    state.pendingLevel = key;
    $("#extremeIntro").classList.add("show");
    return;
  }
  launchLevel(key);
}

function takeMandatoryIfDue() {
  if (state.level !== "extremo") return null;
  if (state.mandatoryIndex >= state.mandatoryCards.length) return null;

  const dueAt = state.mandatorySlots[state.mandatoryIndex];
  if (state.completed < dueAt) return null;

  const card = state.mandatoryCards[state.mandatoryIndex++];
  state.seen.add(card.id);
  return card;
}

function drawNextCard(excludeId = null) {
  const mandatory = takeMandatoryIfDue();
  if (mandatory) return mandatory;

  if (state.noRepeatSession) {
    if (state.level === "extremo" && state.completed < state.bothUnlockAt) {
      const individualIndex = state.unseen.findIndex(card =>
        !state.seen.has(card.id) &&
        card.id !== excludeId &&
        card.for !== "both"
      );

      if (individualIndex >= 0) {
        const card = state.unseen.splice(individualIndex, 1)[0];
        state.seen.add(card.id);
        return card;
      }
    }

    while (state.unseen.length) {
      const card = state.unseen.shift();
      if (!state.seen.has(card.id) && card.id !== excludeId) {
        state.seen.add(card.id);
        return card;
      }
    }
    return null;
  }

  if (!state.unseen.length && state.deferred.length) {
    state.unseen = shuffle(state.deferred);
    state.deferred = [];
    if (excludeId && state.unseen.length > 1 && state.unseen[0].id === excludeId) {
      const swapIndex = state.unseen.findIndex(c => c.id !== excludeId);
      if (swapIndex > 0) {
        [state.unseen[0], state.unseen[swapIndex]] = [state.unseen[swapIndex], state.unseen[0]];
      }
    }
  }
  return state.unseen.shift() || null;
}

function actorIndexFor(card) {
  if (Number.isInteger(card.actorIndex)) return card.actorIndex;
  return state.turn % 2;
}

function actorFor(card) {
  if (card.for === "both") return "Los dos";
  return state.names[actorIndexFor(card)];
}

function targetFor(card) {
  const actorIndex = actorIndexFor(card);
  return state.names[actorIndex === 0 ? 1 : 0];
}

function personalizeCardText(card) {
  const player1 = state.names[0];
  const player2 = state.names[1];
  const hasPlaceholders = /\{actor\}|\{target\}|\{player1\}|\{player2\}/.test(card.text);

  let text = card.text
    .replaceAll("{player1}", player1)
    .replaceAll("{player2}", player2);

  if (card.for === "both") {
    text = text
      .replaceAll("{actor}", player1)
      .replaceAll("{target}", player2);
    return hasPlaceholders ? text : `${player1} y ${player2}: ${text}`;
  }

  const actor = actorFor(card);
  const target = targetFor(card);

  text = text
    .replaceAll("{actor}", actor)
    .replaceAll("{target}", target)
    .replaceAll("Tu pareja", target)
    .replaceAll("tu pareja", target);

  return hasPlaceholders ? text : `${actor}: ${text}`;
}

function pendingCount() {
  return Math.max(0, state.total - state.completed);
}

function renderCard() {
  const card = state.current;
  if (!card) return noMoreCards();

  const data = gameData[state.level];
  $("#gameLevelName").textContent = `${data.icon} ${data.name}`;
  $("#gameProgressText").textContent = `${state.completed} completadas de ${state.total}`;
  $("#gameProgress").style.width = `${(state.completed / state.total) * 100}%`;
  $("#cardType").textContent = card.type;
  $("#turnName").textContent = card.for === "both" ? "Los dos" : `Turno de ${actorFor(card)}`;

  const passText = state.passes ? ` · ${state.passes} paso${state.passes === 1 ? "" : "s"}` : "";
  $("#cardNumber").textContent = `${pendingCount()} pendientes${passText}`;
  $("#cardText").textContent = personalizeCardText(card);

  if (state.level === "fotos") {
    $("#cardHint").textContent = "La app no abre la cámara. Hagan y conserven fotos o videos solo si ambos quieren.";
  } else if (state.level === "extremo" && card.mandatory) {
    $("#cardHint").textContent = "Carta de prenda programada para esta parte de la partida. Paso sigue disponible.";
  } else {
    $("#cardHint").textContent = "";
  }

  const chip = $("#durationChip");
  if (card.duration) {
    chip.textContent = `◷ ${card.duration} s`;
    chip.classList.add("show");
  } else {
    chip.classList.remove("show");
  }

  $("#illustration").innerHTML = illustration(card.illustration);
  updateFavoriteUI();

  const el = $("#challengeCard");
  el.classList.remove("enter");
  void el.offsetWidth;
  el.classList.add("enter");
}

function advanceCard() {
  const card = state.current;
  if (!card) return;

  if (card.for !== "both") {
    if (Number.isInteger(card.actorIndex)) {
      state.turn = card.actorIndex === 0 ? 1 : 0;
    } else {
      state.turn++;
    }
  }
  state.completed++;
  state.current = null;

  if (state.completed >= state.total) return completeLevel();

  state.current = drawNextCard();
  if (!state.current) return noMoreCards();
  renderCard();
}

function passCard() {
  const card = state.current;
  if (!card) return;

  state.passes++;

  if (state.noRepeatSession) {
    state.skipped.push(card);
    state.current = drawNextCard(card.id);
    if (!state.current) return noMoreCards();
    showToast("Paso · no suma y esta carta no se repite");
    renderCard();
    return;
  }

  const otherPending = state.unseen.length + state.deferred.length;
  if (otherPending === 0) {
    state.passes--;
    showToast("Es el último reto pendiente; Paso no lo cuenta.");
    return;
  }

  state.deferred.push(card);
  state.current = drawNextCard(card.id);
  showToast("Paso · no suma y muestra otro reto");
  renderCard();
}

