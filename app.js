function openTimer() {
  const card = state.current;
  const suggested = card && card.duration
    ? Math.min(60, Math.max(15, [15, 30, 60].reduce((a, b) => Math.abs(b - card.duration) < Math.abs(a - card.duration) ? b : a, 30)))
    : 30;
  state.timerDuration = suggested;
  resetTimerVisual(suggested);
  $("#timerModal").classList.add("show");
}
