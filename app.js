function drawNextCard(excludeId = null) {
  const mandatory = takeMandatoryIfDue();
  if (mandatory) return registerDraw(mandatory);

  if (state.noRepeatSession) {
    // En Extremo, las cartas marcadas para ambos empiezan después de 8 cartas mostradas.
    if (state.level === "extremo" && state.shownCount < state.bothUnlockAt) {
      const individualIndex = state.unseen.findIndex(card =>
        !state.seen.has(card.id) &&
        card.id !== excludeId &&
        card.for !== "both"
      );

      if (individualIndex >= 0) {
        const card = state.unseen.splice(individualIndex, 1)[0];
        return registerDraw(card);
      }
    }

    while (state.unseen.length) {
      const card = state.unseen.shift();
      if (!state.seen.has(card.id) && card.id !== excludeId) {
        return registerDraw(card);
      }
    }
    return null;
  }

  if (!state.unseen.length && state.deferred.length) {
    state.unseen = shuffle(state.deferred);
    state.deferred = [];
    if (excludeId && state.unseen.length > 1 && state.unseen[0].id === excludeId) {
      const swapIndex = state.unseen.findIndex(c => c.id !== excludeId);
      if (swapIndex > 0) {
        [state.unseen[0], state.unseen[swapIndex]] = [state.unseen[swapIndex], state.unseen[0]];
      }
    }
  }

  return registerDraw(state.unseen.shift() || null);
}

function actorIndexFor(card) {
  if (Number.isInteger(card.actorIndex)) return card.actorIndex;
  return state.turn % 2;
}

function actorFor(card) {
  if (card.for === "both") return "Los dos";
  return state.names[actorIndexFor(card)];
}

function targetFor(card) {
  const actorIndex = actorIndexFor(card);
  return state.names[actorIndex === 0 ? 1 : 0];
}

function personalizeCardText(card) {
  if (card.preserveText) return card.text;

  const player1 = state.names[0];
  const player2 = state.names[1];
  const hasPlaceholders = /\{actor\}|\{target\}|\{player1\}|\{player2\}/.test(card.text);

  let text = card.text
    .replaceAll("{player1}", player1)
    .replaceAll("{player2}", player2);

  if (card.for === "both") {
    text = text
      .replaceAll("{actor}", player1)
      .replaceAll("{target}", player2);
    return hasPlaceholders ? text : `${player1} y ${player2}: ${text}`;
  }

  const actor = actorFor(card);
  const target = targetFor(card);

  text = text
    .replaceAll("{actor}", actor)
    .replaceAll("{target}", target)
    .replaceAll("Tu pareja", target)
    .replaceAll("tu pareja", target);

  return hasPlaceholders ? text : `${actor}: ${text}`;
}

